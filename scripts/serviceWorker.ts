/** One generation serves its own HTML and complete immutable assets. */
export function generateServiceWorker({ buildId, files }: { buildId: string; files: readonly string[] }): string {
  return `// Generated by vite.config.ts. Do not edit dist/sw.js directly.
const CACHE_PREFIX = 'argus-app-'
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(buildId)}
const PRECACHE_URLS = ${JSON.stringify(files.map((file) => `/${file}`))}
const FALLBACK_URL = '/index.html'

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE_NAME)
      await cache.addAll(PRECACHE_URLS)
      await self.skipWaiting()
    } catch (error) {
      // A failed generation must neither activate nor displace known-good data.
      await caches.delete(CACHE_NAME)
      throw error
    }
  })())
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys()
    const previous = keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
    // Old controlled pages may still request their hashed lazy chunks until
    // controllerchange/reload completes. Keep the last known-good generation.
    const keep = previous.at(-1)
    await Promise.all(keys.filter((key) =>
      (key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME && key !== keep) || key === 'argus-v1',
    ).map((key) => caches.delete(key)))
    await self.clients.claim()
  })())
})

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting()
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return

  if (request.mode === 'navigate') {
    // Never replace this worker's HTML with another build's network HTML.
    // Installation proved the complete generation exists before activation.
    event.respondWith(caches.open(CACHE_NAME).then(async (cache) =>
      (await cache.match(FALLBACK_URL)) || Response.error(),
    ))
    return
  }

  if (PRECACHE_URLS.includes(url.pathname)) {
    event.respondWith(caches.open(CACHE_NAME).then(async (cache) =>
      (await cache.match(url.pathname)) || fetch(request),
    ))
    return
  }

  if (url.pathname.startsWith('/assets/')) {
    event.respondWith(caches.match(request).then((cached) => cached || fetch(request)))
  }
  // All other requests, including future same-origin APIs, bypass shell caches.
})
`
}
